"""Chapter translation instructions reconciled with glossary decisions (PRD § 11, § 13).

Chapter instructions are generated by the model during analysis — before the user reviews
the glossary. The analysis prompt forbids assigning translations of names and terms in instructions,
but the model sometimes violates this: it echoes its suggestions from candidates (e.g. "Translate
Duskmere according to glossary as 'Даскмир'") and selects character gender. When the user subsequently
edits the glossary decision, the chapter instruction remains unchanged and conflicts with the decision
in every processing request. The prompt prioritizes glossary decisions over chapter instructions,
but that is merely guidance. Therefore, instructions that contradict user decisions are pruned
from processing context.

Contradictions are identified deterministically and only where reliable:

- the instruction mentions the concept: original spelling (`glossary_key`), user translation variant,
  model variant from this chapter's analysis, and for characters — individual name components
  (instructions typically refer to "Ren" rather than "Ren Calder");
- and quotes an alternative translation variant: model suggestion rejected by the user, or a word
  sharing the same root as the user variant but not being its grammatical form ("Даскмир" when
  decision is "Даскмер");
- or specifies a grammatical gender different from that in the decision's guidance. Gender is
  compared only if the decision specifies it.

In addition, unquoted mentions of rejected model suggestions are also treated as contradictions
("Use glossary terms (..., Даскмир) consistently"): there is no need for instructions to name
a variant replaced by the user. Grammatical forms are recognized as well.

Rejected variants are gathered from candidates across all book chapters, not just one chapter:
a chapter analysis does not re-emit candidates already established in previous chapters,
yet chapter instructions might still echo earlier model variants.

Other guidance — narrator voice, character speech quirks, register — is preserved even if it
mentions the concept. Unrecognized contradictions are handled by prompt priority.

Instructions are split into items by lines (numbered lists). A line without a list marker
continues the preceding item. Unformatted paragraphs are split into sentences so that a single
contradiction does not discard the entire instruction block.
"""

from __future__ import annotations

import re
from collections.abc import Iterable, Sequence
from dataclasses import dataclass

from linguary.domain import (
    ConceptType,
    GlossaryCandidate,
    GlossarySnapshotEntry,
    glossary_key,
)

#: List item marker at line start: `1.`, `2)`, `-`, `•`, `*`.
_ITEM_MARKER = re.compile(r"^\s*(?:\d+[.)]|[-•*–—])\s")

#: Sentence boundary in unformatted instruction paragraphs.
_SENTENCE_END = re.compile(r"(?<=[.!?;])\s+")

#: Quoted fragment: guillemets, German quotes, English curly and straight quotes.
_QUOTED = re.compile(r"«([^»]+)»|„([^“”]+)[“”]|“([^”]+)”|\"([^\"]+)\"")

#: Word: letters and digits, optionally with internal apostrophe or hyphen.
_WORD = re.compile(r"\w+(?:['’-]\w+)*")

#: Grammatical gender in guidance: "мужской род", "женский род".
_GENDER = re.compile(r"\b(мужск|женск|средн)\w*\s+род\w*", re.IGNORECASE)

#: Salutations and honorifics not considered part of a name.
_TITLES = frozenset(
    {
        *("mr", "mrs", "ms", "dr", "st", "sir", "lady", "lord", "miss"),
        *("мистер", "миссис", "мисс", "доктор", "сэр", "леди", "лорд"),
    }
)

#: Minimum name component length used to associate instruction with a character.
_MIN_NAME_PART = 3

#: Maximum inflected word ending beyond shared stem, and minimum shared stem length
#: for quotes to be considered variants of the same concept.
_MAX_ENDING = 3
_MIN_SHARED_PREFIX = 3


@dataclass(frozen=True, slots=True)
class _Decision:
    """User decision as formatted for instruction comparison."""

    mentions: tuple[tuple[str, ...], ...]
    translation: tuple[str, ...]
    source_key: str
    rejected: frozenset[str]
    rejected_words: tuple[tuple[str, ...], ...]
    genders: frozenset[str]


def instructions_respecting_glossary(
    instructions: str,
    *,
    decisions: Sequence[GlossarySnapshotEntry],
    chapter_candidates: Iterable[GlossaryCandidate] = (),
) -> str:
    """Chapter instructions with items contradicting user decisions removed.

    `decisions` — mandatory decisions from the run snapshot, `chapter_candidates` — candidates
    from book chapter analyses whose variants might be echoed in instructions.
    """
    if not decisions or not instructions.strip():
        return instructions.strip()
    prepared = _prepare(decisions, chapter_candidates)
    kept = [
        item
        for item in _items(instructions)
        if not _contradicts(item, prepared) and not _names_rejected(item, prepared)
    ]
    return "\n".join(kept).strip()


def note_respecting_glossary(
    entry: GlossarySnapshotEntry | GlossaryCandidate,
    *,
    decisions: Sequence[GlossarySnapshotEntry],
    chapter_candidates: Iterable[GlossaryCandidate] = (),
) -> str:
    """Glossary entry guidance with fragments conflicting with other decisions pruned.

    Guidance of an entry accepted without edits was written by the model during analysis
    and may echo its rejected suggestions for other concepts: e.g. "gate near Duskmere",
    even though the user's decision for Duskmere is "Даскмер".

    Storage does not distinguish user-authored guidance from model guidance accepted as-is,
    so we only filter out contradictions with user decisions on *other* concepts: an entry's
    guidance is entitled to discuss its own concept.
    """
    note = entry.note.strip()
    key = glossary_key(entry.source_text)
    others = [
        decision
        for decision in decisions
        if decision.status.is_user_decision
        and glossary_key(decision.source_text) != key
    ]
    if not others or not note:
        return note
    prepared = _prepare(others, chapter_candidates)
    items = _items(note)
    kept = [
        item
        for item in items
        if not _contradicts(item, prepared) and not _names_rejected(item, prepared)
    ]
    if len(kept) == len(items):
        return note
    return " ".join(line.strip() for item in kept for line in item.splitlines()).strip()


def _names_rejected(item: str, decisions: Sequence[_Decision]) -> bool:
    """Whether fragment mentions, even unquoted, a variant rejected by the user."""
    words = _words(item)
    return any(
        _contains(words, rejected)
        for decision in decisions
        for rejected in decision.rejected_words
    )


def _prepare(
    decisions: Sequence[GlossarySnapshotEntry],
    chapter_candidates: Iterable[GlossaryCandidate],
) -> tuple[_Decision, ...]:
    """Decisions with mention forms, rejected variants, and grammatical gender."""
    suggested: dict[str, set[str]] = {}
    for candidate in chapter_candidates:
        suggested.setdefault(glossary_key(candidate.source_text), set()).add(
            candidate.suggested_translation
        )
    prepared = []
    for entry in decisions:
        key = glossary_key(entry.source_text)
        translation_key = glossary_key(entry.translation)
        rejected = {
            glossary_key(text)
            for text in suggested.get(key, ())
            if glossary_key(text) != translation_key
        }
        forms = [entry.source_text, entry.translation, *suggested.get(key, ())]
        mentions = {_words(form) for form in forms}
        if entry.type is ConceptType.PERSON:
            mentions.update(
                (part,)
                for form in forms
                for part, original in zip(_words(form), _WORD.findall(form), strict=True)
                if original[:1].isupper()
                and len(part) >= _MIN_NAME_PART
                and part not in _TITLES
            )
        prepared.append(
            _Decision(
                mentions=tuple(mention for mention in mentions if mention),
                translation=_words(entry.translation),
                source_key=key,
                rejected=frozenset(rejected),
                rejected_words=tuple(
                    words
                    for text in suggested.get(key, ())
                    if glossary_key(text) in rejected
                    and (words := _words(text))
                    and not _is_form_of(words, _words(entry.translation))
                ),
                genders=_genders(entry.note),
            )
        )
    return tuple(prepared)


def _items(instructions: str) -> list[str]:
    """Instruction items: list lines with continuations, or paragraph sentences."""
    items: list[str] = []
    marked = False
    for line in instructions.strip().splitlines():
        if not line.strip():
            continue
        if _ITEM_MARKER.match(line):
            marked = True
            items.append(line.rstrip())
        elif items and marked:
            items[-1] = f"{items[-1]}\n{line.rstrip()}"
        else:
            items.append(line.rstrip())
    if marked or len(items) != 1:
        return items
    return [sentence for sentence in _SENTENCE_END.split(items[0]) if sentence.strip()]


def _contradicts(item: str, decisions: Sequence[_Decision]) -> bool:
    """Whether an instruction item contradicts any user decision."""
    words = _words(item)
    genders = _genders(item)
    quoted = tuple(
        next(group for group in match.groups() if group is not None)
        for match in _QUOTED.finditer(item)
    )
    for decision in decisions:
        if not any(_contains(words, mention) for mention in decision.mentions):
            continue
        if decision.genders and genders and not genders <= decision.genders:
            return True
        if any(_other_translation(text, decision) for text in quoted):
            return True
    return False


def _other_translation(quoted: str, decision: _Decision) -> bool:
    """Whether a quoted fragment names a translation variant differing from decision."""
    key = glossary_key(quoted)
    if key == decision.source_key:
        return False
    if key in decision.rejected:
        return True
    words = _words(quoted)
    if not words or _is_form_of(words, decision.translation):
        return False
    return any(
        _shared_prefix(word, other) >= _MIN_SHARED_PREFIX and not _same_word(word, other)
        for word in words
        for other in decision.translation
    )


def _is_form_of(words: Sequence[str], translation: Sequence[str]) -> bool:
    """Whether words represent a grammatical inflected form of user translation."""
    return all(any(_same_word(word, other) for other in translation) for word in words)


def _contains(words: Sequence[str], mention: Sequence[str]) -> bool:
    """Whether mention occurs consecutively in text, up to word forms."""
    size = len(mention)
    return any(
        all(
            _same_word(word, expected)
            for word, expected in zip(words[start : start + size], mention, strict=True)
        )
        for start in range(len(words) - size + 1)
    )


def _same_word(word: str, expected: str) -> bool:
    """Whether `word` is an inflected form of `expected`: shared stem and short ending.

    Stem is the entire word minus the last letter: in Russian names it inflects
    ("Селена" — "Селены"), while in English it matches completely.
    """
    if word == expected:
        return True
    stem = max(len(expected) - 1, _MIN_NAME_PART)
    return (
        _shared_prefix(word, expected) >= stem
        and abs(len(word) - len(expected)) <= _MAX_ENDING
    )


def _shared_prefix(first: str, second: str) -> int:
    """Length of shared prefix of two words."""
    length = 0
    for left, right in zip(first, second, strict=False):
        if left != right:
            break
        length += 1
    return length


def _words(text: str) -> tuple[str, ...]:
    """Words of text lowercased without punctuation."""
    return tuple(word.casefold().replace("’", "'") for word in _WORD.findall(text))


def _genders(text: str) -> frozenset[str]:
    """Grammatical genders mentioned in text."""
    return frozenset(match.group(1).casefold() for match in _GENDER.finditer(text))


__all__ = ["instructions_respecting_glossary", "note_respecting_glossary"]
